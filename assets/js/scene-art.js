/* 一排书脊，放在书架上。 */
function books(x, y, w, h, seed = 1, palette = ["#b97f88", "#d8b98e", "#8fae9a", "#a9a2c4", "#e0bcae"]) {
  let out = "";
  let cursor = x;
  let i = 0;
  while (cursor < x + w - 2) {
    const bw = 4 + ((i * 5 + seed) % 6);
    const bh = h - ((i * 7 + seed) % 7);
    out += R(cursor, y + h - bh, bw, bh, palette[(i + seed) % palette.length], 1);
    cursor += bw + 2;
    i += 1;
  }
  return out;
}

/* 货架上的彩色瓶子 / 盒子。 */
function goods(x, y, w, h, seed = 1) {
  const palette = ["#e8a08c", "#f3d9a6", "#a8c9a0", "#b7a4d8", "#8bb8d8", "#d8b98e"];
  let out = "";
  let cursor = x;
  let i = 0;
  while (cursor < x + w - 5) {
    const gw = 6 + ((i * 3 + seed) % 5);
    const gh = h - ((i * 5 + seed) % 6);
    out += R(cursor, y + h - gh, gw, gh, palette[(i + seed) % palette.length], 2);
    out += R(cursor + 1, y + h - gh + 1.5, gw - 2, 2, "#fffaf0", 1, ' opacity=".55"');
    cursor += gw + 2;
    i += 1;
  }
  return out;
}

