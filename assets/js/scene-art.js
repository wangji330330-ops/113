const LEAF2 = "#8fb98f";
const PINK = "#e9a0b0";
const INK = "#8b7566";

/* ------------------------------------------------------------------ *
 * 画 SVG 的小积木
 * ------------------------------------------------------------------ */

const R = (x, y, w, h, fill, rx = 0, extra = "") =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}"${rx ? ` rx="${rx}"` : ""} fill="${fill}"${extra}/>`;

const E = (cx, cy, rx, ry, fill, extra = "") =>
  `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}"${extra}/>`;

const C = (cx, cy, r, fill, extra = "") =>
  `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill}"${extra}/>`;

const P = (d, fill = "none", extra = "") => `<path d="${d}" fill="${fill}"${extra}/>`;

const PL = (points, fill, extra = "") => `<polygon points="${points}" fill="${fill}"${extra}/>`;

const S = (d, stroke, width = 1.2, extra = "") =>
  `<path d="${d}" fill="none" stroke="${stroke}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"${extra}/>`;

/* 房间：墙、护墙板、地脚线、地板、几块地板缝。 */
function roomBase(p, fy = 170, wall2 = "#f4e7da", floor = "#e7d3bf") {
  return (
    R(0, 0, W, H, p.wall) +
    R(0, 0, W, 22, wall2, 0, ' opacity=".55"') +
    R(0, fy - 46, W, 46, wall2, 0, ' opacity=".32"') +
    R(0, fy - 6, W, 6, WOOD2, 0, ' opacity=".22"') +
    R(0, fy, W, H - fy, floor) +
    S(`M0 ${fy + 12}H320`, SHADE, 1, ' opacity=".6"') +
    S(`M0 ${fy + 25}H320`, SHADE, 1, ' opacity=".38"') +
    S(`M78 ${fy + 1}L64 200M196 ${fy + 1}L208 200M288 ${fy + 1}L302 200`, SHADE, 1, ' opacity=".3"')
  );
}

/* 一串小星星。 */
function stars(list, color = "#fff4d6") {
  return list
    .map(([x, y, r = 1.2], i) => C(x, y, r, color, ` opacity="${i % 3 === 0 ? 0.95 : 0.55}"`))
    .join("");
}

/* 一团云。 */
function cloud(x, y, s = 1, color = CREAM, opacity = 0.9) {
  return (
    E(x, y, 22 * s, 8 * s, color, ` opacity="${opacity}"`) +
    E(x - 12 * s, y - 5 * s, 13 * s, 8 * s, color, ` opacity="${opacity}"`) +
    E(x + 9 * s, y - 6 * s, 15 * s, 9 * s, color, ` opacity="${opacity}"`) +
    E(x + 22 * s, y - 1 * s, 11 * s, 7 * s, color, ` opacity="${opacity}"`)
  );
}

/* 午后/黄昏的太阳，用三层同心圆代替渐变。 */
function sun(cx, cy, r, halo = WARM) {
  return (
    C(cx, cy, r * 2.3, halo, ' opacity=".06"') +
    C(cx, cy, r * 1.5, halo, ' opacity=".1"') +
    C(cx, cy, r, halo, ' opacity=".82"')
  );
}

/* 灯光：只在光源附近叠两三层淡淡的圆，不用渐变，也不会画出一圈圈的轮廓。 */
function halo(cx, cy, r, color = WARM, strength = 0.14) {
  return (
    C(cx, cy, r, color, ` opacity="${(strength * 0.38).toFixed(3)}"`) +
    C(cx, cy, r * 0.56, color, ` opacity="${(strength * 0.42).toFixed(3)}"`) +
    C(cx, cy, r * 0.28, color, ` opacity="${(strength * 0.5).toFixed(3)}"`)
  );
}

/* 一盆小植物。 */
