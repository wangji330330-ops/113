/*
 * 13 个地方的柔和手绘风背景。
 * 纯 SVG、零依赖、不联网、没有外部图片。
 * 画布 320×200，地板线在 y≈170，人物站位附近保持干净。
 * 只用 rect / circle / ellipse / path / polygon，颜色全部是低饱和的奶油、雾蓝、樱粉、抹茶绿。
 */

const W = 320;
const H = 200;

/* 共用底色：所有场景都从这里取色，换成整体换季只改这一块。 */
const SHADE = "#d9c3ae";
const WOOD = "#cfa581";
const WOOD2 = "#a97f5f";
const CREAM = "#fff9f0";
const WARM = "#ffd9a0";
const COOL = "#c9d4ee";
