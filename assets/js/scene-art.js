function buildSvg(entry, { className = "", ratio = "16 / 10" } = {}) {
  const klass = String(className || "").replace(/["<>]/g, "");
  const rate = String(ratio || "16 / 10").replace(/["<>]/g, "");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 200" preserveAspectRatio="xMidYMid slice"` +
    (klass ? ` class="${klass}"` : "") +
    ` role="img" aria-hidden="true" data-ratio="${rate}" style="display:block;width:100%;height:100%;aspect-ratio:${rate}">` +
    entry.art(entry.palette) +
    "</svg>"
  );
}

export const SCENES = {};
for (const [id, entry] of Object.entries(ART)) {
  entry.id = id;
  SCENES[id] = {
    name: entry.name,
    palette: entry.palette,
    render: (options = {}) => buildSvg(entry, options)
  };
}
for (const entry of Object.values(ART)) {
  SCENES[entry.id].svg = buildSvg(entry, {});
}

export const SCENE_IDS = Object.keys(SCENES);

export function sceneSvg(placeId, options = {}) {
  const scene = SCENES[placeId] || SCENES[SCENE_IDS[0]];
  return scene.render(options);
}