const VALID = new Set([".", "#", "+"]);

function normalize(name) {
  const rows = ICONS[name] || ICONS.spark;
  return rows.map((row) => {
    const clean = row.slice(0, 12).replace(/[^#+.]/g, ".");
    return clean.padEnd(12, ".");
  });
}

/**
 * Render a 12×12 icon as inline SVG.
 * The icon inherits `currentColor`; "+" uses `--icon-accent`.
 */
export function icon(name, className = "") {
  const rows = normalize(name);
  let shapes = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 12) {
      const char = row[x];
      if (!VALID.has(char) || char === ".") {
        x += 1;
        continue;
      }
      let width = 1;
      while (x + width < 12 && row[x + width] === char) width += 1;
      const fill = char === "+" ? ' class="px-icon__alt"' : "";
      shapes += `<rect x="${x}" y="${y}" width="${width}" height="1"${fill}/>`;
      x += width;
    }
  });
  return `<svg class="px-icon ${className}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${shapes}</svg>`;
}

export function iconTile(name, extra = "") {
  return `<span class="icon-tile ${extra}">${icon(name)}</span>`;
}
